'use client';

import React from 'react';
import type { SATQuestion, SATBlock, SATSheet, SATRect } from '@/lib/sat-types';

import katex from 'katex';

// PDF points → CSS pixels. Source text is ~9pt, so this renders it at ~18px,
// matching the site's body copy. Sheets are rasterised at 2.5–3 px/pt, so crops stay
// sharp on 2x displays.
const CSS_PX_PER_PT = 2.0;

/** One crop out of a question's sprite sheet. Responsive: shrinks to fit narrow screens. */
export function SheetCrop({ sheet, rect, alt }: { sheet: SATSheet; rect: SATRect; alt: string }) {
  const cssWidth = (rect.w / sheet.scale) * CSS_PX_PER_PT;
  const posX = sheet.w === rect.w ? 0 : (rect.x / (sheet.w - rect.w)) * 100;
  const posY = sheet.h === rect.h ? 0 : (rect.y / (sheet.h - rect.h)) * 100;
  return (
    <span
      role="img"
      aria-label={alt || 'Question figure'}
      className={`sat-crop sat-crop--${sheet.mode}`}
      style={{
        width: '100%',
        maxWidth: `${cssWidth}px`,
        aspectRatio: `${rect.w} / ${rect.h}`,
        backgroundImage: `url(${sheet.src})`,
        backgroundSize: `${(sheet.w / rect.w) * 100}% auto`,
        backgroundPosition: `${posX}% ${posY}%`,
      }}
    />
  );
}

// Dataset text is generated by our extractor (already HTML-escaped) and only uses <i>/<u>.
// Strip anything else defensively before injecting.
export function safeInline(html: string): string {
  return html.replace(/<(?!\/?(i|u|b|strong|em)>)[^>]*>/g, '');
}

/**
 * Currency-aware KaTeX math tokenizer and renderer.
 * Prevents collisions between dollar currency signs (e.g. "$15 in the morning and $25 at night")
 * and inline/display LaTeX math blocks ($...$, $$...$$, \(...\), \[...\]).
 */
export function renderWithMath(content: string): string {
  if (!content) return '';

  // 1. Currency-aware tokenizer: Protect currency dollar amounts like $15, $25.50, $1,000
  // Any $ immediately followed by a digit and a word boundary/space/comma/period/end of string
  const CURRENCY_REGEX = /\$(\d+(?:,\d{3})*(?:\.\d{1,2})?)(?=\s|[.,;!?]|$)/g;
  const CURRENCY_TOKEN = '___CURRENCY_DOLLAR___';
  const ESCAPED_DOLLAR_TOKEN = '___ESCAPED_DOLLAR___';

  // Protect literal escaped dollars \$
  let text = content.replace(/\\\$/g, ESCAPED_DOLLAR_TOKEN);

  // Protect currency amounts
  text = text.replace(CURRENCY_REGEX, `${CURRENCY_TOKEN}$1`);

  // 2. Render display math $$...$$
  text = text.replace(/\$\$([\s\S]+?)\$\$/g, (_, math) => {
    try {
      return katex.renderToString(math.trim(), { displayMode: true, throwOnError: false, strict: 'ignore' });
    } catch {
      return `<span class="katex-error">${math}</span>`;
    }
  });

  // Render display math \[...\]
  text = text.replace(/\\\[([\s\S]+?)\\\]/g, (_, math) => {
    try {
      return katex.renderToString(math.trim(), { displayMode: true, throwOnError: false, strict: 'ignore' });
    } catch {
      return `<span class="katex-error">${math}</span>`;
    }
  });

  // 3. Render inline math $...$
  text = text.replace(/\$([^\$\n]+?)\$/g, (match, math) => {
    // If it looks purely like an unprotected price or number without math symbols, leave it
    if (/^\s*\d+([.,]\d+)?\s*$/.test(math)) {
      return match;
    }
    try {
      return katex.renderToString(math.trim(), { displayMode: false, throwOnError: false, strict: 'ignore' });
    } catch {
      return match;
    }
  });

  // 4. Render inline math \(...\)
  text = text.replace(/\\\(([\s\S]+?)\\\)/g, (match, math) => {
    try {
      return katex.renderToString(math.trim(), { displayMode: false, throwOnError: false, strict: 'ignore' });
    } catch {
      return match;
    }
  });

  // 5. Restore currency and escaped dollars
  text = text.replace(new RegExp(CURRENCY_TOKEN, 'g'), '$');
  text = text.replace(new RegExp(ESCAPED_DOLLAR_TOKEN, 'g'), '$');

  return text;
}

export function RichText({ html, className }: { html: string; className?: string }) {
  const sanitized = safeInline(html);
  const rendered = renderWithMath(sanitized);
  return <span className={className} dangerouslySetInnerHTML={{ __html: rendered }} />;
}

function Blocks({ blocks, sheet, className }: { blocks: SATBlock[]; sheet?: SATSheet; className?: string }) {
  return (
    <div className={className}>
      {blocks.map((b, i) =>
        b.type === 'text' ? (
          <p key={i} className="sat-para">
            <RichText html={b.html} />
          </p>
        ) : sheet ? (
          <div key={i} className="sat-figure">
            <SheetCrop sheet={sheet} rect={b} alt={b.alt} />
          </div>
        ) : (
          <p key={i} className="sat-para">{b.alt}</p>
        )
      )}
    </div>
  );
}

/** Legacy questions (e.g. old Mistake Vault entries) only carry plain `prompt` text. */
function stemBlocks(q: SATQuestion): SATBlock[] {
  if (q.stem && q.stem.length) return q.stem;
  return (q.prompt || '').split(/\n{2,}/).map((t) => ({ type: 'text' as const, html: escapeHtml(t) }));
}

function escapeHtml(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/**
 * Splits a Reading & Writing stem into passage + question, as Bluebook shows them
 * side by side. The question is the final text paragraph ("Which choice ...").
 */
export function splitPassage(q: SATQuestion): { passage: SATBlock[]; question: SATBlock[] } {
  const blocks = stemBlocks(q);
  if (q.section !== 'reading-writing' || blocks.length < 2) return { passage: [], question: blocks };
  const last = blocks[blocks.length - 1];
  if (last.type !== 'text') return { passage: [], question: blocks };
  return { passage: blocks.slice(0, -1), question: [last] };
}

export function QuestionStem({ q, only }: { q: SATQuestion; only?: 'passage' | 'question' }) {
  let blocks = stemBlocks(q);
  if (only) {
    const split = splitPassage(q);
    blocks = only === 'passage' ? split.passage : split.question;
  }
  return <Blocks blocks={blocks} sheet={q.sheet} className="sat-stem" />;
}

export function ChoiceContent({ q, index }: { q: SATQuestion; index: number }) {
  const media = q.choiceMedia?.[index];
  const text = q.choices?.[index] || '';
  if (media && media.length && q.sheet) {
    return (
      <span className="sat-choice-media">
        {media.map((r, i) => (
          <SheetCrop key={i} sheet={q.sheet!} rect={r} alt={text || `Choice ${String.fromCharCode(65 + index)}`} />
        ))}
      </span>
    );
  }
  return <RichText html={text} className="sat-choice-text" />;
}

export function Rationale({ q }: { q: SATQuestion }) {
  if (q.rationaleBlocks && q.rationaleBlocks.length) {
    return <Blocks blocks={q.rationaleBlocks} sheet={q.rationaleSheet} className="sat-rationale" />;
  }
  return (
    <div className="sat-rationale">
      {(q.rationale || 'No rationale provided.').split(/\n{2,}/).map((p, i) => (
        <p key={i} className="sat-para">{p}</p>
      ))}
    </div>
  );
}
